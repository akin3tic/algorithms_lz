import random
sl = sorted(random.sample(range(0, 201), 101))#search list список для поиска 100 чисел от 0 до 200
e = 50 #element to search
d = len(sl) #длина списка
c1 = 0 # счетчик сравнений для линейного поиска
w = -1 #чтобы не писало не найдено если первый элемент нужный
print("начальный список: ", sl)
print("ЛИНЕЙНЫЙ ПОИСК:")
for i in range(d):
    c1 +=1 #засчитывание счетчика для линейного поиска
    if e == sl[i]: #сравнивает искомый элемент с элементом списка
        w=i #если значения совпали то w принимает значение его индекса
        break
if w !=-1: #эта проверка нужна только для коректного вывода
    print("индекс элемента: ", w)
    print("количество сравнений: ", c1)
else:
    print("число не найдено")

print("БИНАРНЫЙ ПОИСК: ")
l = 0 # нижняя граница поиска
h = len(sl)-1 # верхняя граница поиска
c2 = 0 # счетчик сравнений для бинарного поиска
w2=-1 #значение -1 так как если будет 0 то при верном первом элементе будет всегда выводить число не найдено
while l<=h: #кароч условие цикла хз че еще сюда написать
    c2+=1 #засчитывание операции и бла бла бла
    m = (l+h)//2 # среднее значение
    if sl[m] == e: #условие сравнение с искомым элементом
        w2 = m #кароч берем крутой индекс
        break #стопим когда его нашли
    elif sl[m] < e: #ну тупо второе условие по кайфу чтобы понять какую границу нужно урезать
        l = m+1 #обрезание 1
    else: #ну тип понятно что если значение неравно и небольше то оно меньше и верх можно отчикрыжить
        h = m-1 #обрезание 2
if w2 == -1: #чиловое условие для коррррректного вывода
    print("число не найдено") 
else:
    print("индекс элемента: ", w2)
    print("количество сравнений: ", c2)
    