import random
nsl = [random.randint(0,1000000) for i in range(100)]#not sorted list не отсортированный начальный список
nsl2 = nsl.copy() #копируем список
c = 0 #счетчик перемещений для пузырька
i = 0
print("начальный список: ", nsl)
print("СОРТИРОВКА ПУЗЫРЕК:")
while i<len(nsl)-1: 
    c+=1 #засчитывает сравнения
    if nsl[i]<nsl[i+1]: #условие для обмена элементов
        nsl[i],nsl[i+1]=nsl[i+1],nsl[i] #обмен элементов
        i=0
        print(nsl)
    else:
        i+=1
print("отсортированный список пузырьком: ", nsl)
print("количество сравнений: ", c)
c2 = 0 #счетчик перемещений для выбора
print("СОРТИРОВКА ВЫБОРОМ:")
for j in range(len(nsl2)): #первый цикл который определяет первый элемент как максимальный
    max=j
    for k in range(j+1,len(nsl2)): #второй циклл который ищет настоящий максимальный элемент
        c2+=1 #засчитывает сравнения
        if nsl2[k]>nsl2[max]:
            max=k
    if max != j: #если максимальный элемент изменился то меняет его с начальным значением максимального элемента
        nsl2[j],nsl2[max]=nsl2[max],nsl2[j] #обмен элементов местами
        print(nsl2)
print("отсортированный список выбором: ", nsl2)
print("количество сравнений: ", c2) #мне кажется это никто читать не будет